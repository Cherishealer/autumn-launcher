// Match fixed UI labels exactly. Diagnostics may contain values interpolated by
// the main process, so only longer known fragments are translated in fallback.
const fragments = Object.entries(english).filter(([source]) => source.length >= 6 || source === '（退出码' || /^(?:Xbox |Minecraft )/.test(source)).sort((a, b) => b[0].length - a[0].length);
export function translate(text: string, language: Language): string {
  if (language === 'zh-CN') return text;
  const key = text.trim();
  if (Object.hasOwn(english, key)) return text.replace(key, english[key]);
  let result = text.replace(/^游戏(异常退出|未完成启动)/, (_match, status) => status === '异常退出' ? 'Game exited abnormally' : 'Game did not finish starting');
  for (const [source, target] of fragments) result = result.split(source).join(target);
  return result.replace(/失败(?=（HTTP|\(HTTP)/g, ' failed').replace(/游戏(?=异常退出|未完成启动)/g, 'Game').replaceAll('（', ' (').replaceAll('）', ')').replaceAll('；', '; ').replaceAll('。', '. ');
}
